    private void setupTabel() {
    modelTabel = new javax.swing.table.DefaultTableModel(KOLOM, 0) {
        @Override
        public boolean isCellEditable(int r, int c) { return false; }
    };
    jTable1 = new javax.swing.JTable(modelTabel);
    jTable1.setSelectionMode(javax.swing.ListSelectionModel.SINGLE_SELECTION);
    jTable1.setRowHeight(25);
    jTable1.getSelectionModel().addListSelectionListener(e -> {
        if (!e.getValueIsAdjusting()) isiFormDariTabel();
    });
    jScrollPane1 = new javax.swing.JScrollPane(jTable1);
    jScrollPane1.setBounds(10, 310, 460, 180);
    getContentPane().add(jScrollPane1);
    setSize(500, 540);
}

private void isiDummyData() {
    modelTabel.setRowCount(0);
    modelTabel.addRow(new Object[]{1, "Laskar Pelangi",  "Andrea Hirata",    "978-001", "Fiksi",     "Tersedia"});
    modelTabel.addRow(new Object[]{2, "Bumi Manusia",    "Pramoedya Ananta", "978-002", "Sejarah",   "Dipinjam"});
    modelTabel.addRow(new Object[]{3, "Clean Code",      "Robert Martin",    "978-003", "Teknologi", "Tersedia"});
}

private void isiFormDariTabel() {
    int baris = jTable1.getSelectedRow();
    if (baris == -1) return;
    idDipilih = (int) modelTabel.getValueAt(baris, 0);
    jTextField2.setText((String) modelTabel.getValueAt(baris, 1));
    jTextField3.setText((String) modelTabel.getValueAt(baris, 2));
    jTextField4.setText((String) modelTabel.getValueAt(baris, 3));
    jTextField5.setText((String) modelTabel.getValueAt(baris, 4));
    jComboBox1.setSelectedItem(modelTabel.getValueAt(baris, 5));
    jButton4.setEnabled(true);
    jButton5.setEnabled(true);
}

private void bersihkanForm() {
    jTextField1.setText("");
    jTextField2.setText("");
    jTextField3.setText("");
    jTextField4.setText("");
    jTextField5.setText("");
    jComboBox1.setSelectedIndex(0);
    idDipilih = -1;
    jButton4.setEnabled(false);
    jButton5.setEnabled(false);
    jTable1.clearSelection();
}

private boolean validasiForm() {
    if (jTextField2.getText().trim().isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(this, "Judul tidak boleh kosong!");
        return false;
    }
    if (jTextField3.getText().trim().isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(this, "Pengarang tidak boleh kosong!");
        return false;
    }
    return true;
}

