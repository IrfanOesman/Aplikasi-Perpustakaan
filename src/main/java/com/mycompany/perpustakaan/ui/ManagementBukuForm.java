    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
        if (!validasiForm()) return;
        modelTabel.addRow(new Object[]{
        modelTabel.getRowCount() + 1,
        jTextField2.getText().trim(),
        jTextField3.getText().trim(),
        jTextField4.getText().trim(),
        jTextField5.getText().trim(),
        jComboBox1.getSelectedItem()
    });
    bersihkanForm();
    javax.swing.JOptionPane.showMessageDialog(this, "Buku berhasil ditambahkan!");
    }//GEN-LAST:event_jButton3ActionPerformed

    private void jButton4ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton4ActionPerformed
    if (idDipilih == -1 || !validasiForm()) return;
    int baris = jTable1.getSelectedRow();
    modelTabel.setValueAt(jTextField2.getText().trim(), baris, 1);
    modelTabel.setValueAt(jTextField3.getText().trim(), baris, 2);
    modelTabel.setValueAt(jTextField4.getText().trim(), baris, 3);
    modelTabel.setValueAt(jTextField5.getText().trim(), baris, 4);
    modelTabel.setValueAt(jComboBox1.getSelectedItem(),  baris, 5);
    bersihkanForm();
    javax.swing.JOptionPane.showMessageDialog(this, "Buku berhasil diperbarui!");
    }//GEN-LAST:event_jButton4ActionPerformed

    private void jButton5ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton5ActionPerformed
        if (idDipilih == -1) return;
    int konfirmasi = javax.swing.JOptionPane.showConfirmDialog(
        this, "Yakin ingin menghapus buku ini?", "Konfirmasi Hapus",
        javax.swing.JOptionPane.YES_NO_OPTION);
    if (konfirmasi == javax.swing.JOptionPane.YES_OPTION) {
        modelTabel.removeRow(jTable1.getSelectedRow());
        bersihkanForm();
        javax.swing.JOptionPane.showMessageDialog(this, "Buku berhasil dihapus!");}
    }//GEN-LAST:event_jButton5ActionPerformed

